#!/usr/bin/env bash
. "$DEPLOY_DIR/tests/lib.sh"

for setting in \
    'POKETTO_NETWORK_SUBNET=0.0.0.0/0' \
    'POKETTO_NETWORK_SUBNET=172.0.0.0/8' \
    'POKETTO_NETWORK_SUBNET=192.168.1.1/24' \
    'POKETTO_NETWORK_SUBNET=10.0.0.0/31' \
    'POKETTO_NETWORK_SUBNET=172.29.230.0/30' \
    'POKETTO_NETWORK_SUBNET=172.29.230.0/29' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.128/30' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.128/31' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.128/32' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.0/24' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.0/23' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.0/25' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.231.128/25' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.29.230.129/25' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=172.029.230.128/25' \
    'POKETTO_NETWORK_DYNAMIC_RANGE=::/64' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.231.10' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.0' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.1' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.255' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.128' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.254' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.010' \
    'POKETTO_GATEWAY_INTERNAL_IP=172.29.230.10/24' \
    'POKETTO_GATEWAY_INTERNAL_IP=.*'; do
    setup_root
    have_image "$DIGEST_IMAGE"
    printf '%s\n' "$setting" >> "$ROOT/.env"
    run_deploy
    assert_status 1
    assert_contains "$ERR" 'POKETTO_'
    [ "$(up_count)" = 0 ]
done

for pair in '10.20.0.0/16 10.20.128.0/17 10.20.0.10' \
    '172.16.0.0/12 172.24.0.0/13 172.16.0.10' \
    '192.168.0.0/16 192.168.128.0/17 192.168.0.10' \
    '172.29.230.0/28 172.29.230.8/29 172.29.230.2' \
    '172.29.230.0/28 172.29.230.0/29 172.29.230.10'; do
    setup_root
    have_image "$DIGEST_IMAGE"
    read -r subnet pool gateway <<< "$pair"
    printf '%s\n' "POKETTO_NETWORK_SUBNET=$subnet" "POKETTO_NETWORK_DYNAMIC_RANGE=$pool" "POKETTO_GATEWAY_INTERNAL_IP=$gateway" >> "$ROOT/.env"
    run_deploy
    assert_status 0
done
